/// Layout width breakpoints, matching Material 3's "medium"/"expanded"
/// window size classes.
class AppBreakpoints {
  AppBreakpoints._();

  /// At or above this width, the web build swaps the phone-style bottom
  /// nav for a side nav rail — the bottom nav stretched across a desktop
  /// browser window looks and behaves like an afterthought.
  static const double sideNav = 840;
}
